// Rebuilds engine/engine.mjs from bist-charts' own source, so the bot runs the exact code the backtests ran.
//
//   npm run sync-engine                         bundle bist-charts' committed HEAD (../bist-charts)
//   npm run sync-engine -- --repo <path>        another checkout
//   npm run sync-engine -- --worktree           bundle the working tree instead of HEAD (stamped as such)
//
// Writes engine/engine.mjs (the bundle), engine/engine.json (where it came from) and engine/golden.json
// (trade-list hashes of fixed strategies on test/fixtures; a change between syncs means bist-charts changed
// how those strategies trade, and the script lists which ones).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const repoArg = args.includes("--repo") ? args[args.indexOf("--repo") + 1] : null;
const repo = resolve(root, repoArg ?? "../bist-charts");
const worktree = args.includes("--worktree");

const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8" }).trim();

if (!existsSync(join(repo, "src/lib/quant/execution-core.ts"))) {
  console.error(`No bist-charts checkout at ${repo} (pass --repo <path>).`);
  process.exit(1);
}

const commit = git("rev-parse", "HEAD");
const commitDate = git("log", "-1", "--format=%cI", "HEAD");
const dirty = git("status", "--porcelain", "--", "src/lib").split("\n").filter(Boolean);

let srcRoot;
let tmp = null;
if (worktree) {
  srcRoot = join(repo, "src");
} else {
  tmp = mkdtempSync(join(tmpdir(), "bist-engine-"));
  // Through a file: src/ is several MB, beyond execFileSync's output buffer.
  const archive = join(tmp, "src.tar");
  execFileSync("git", ["-C", repo, "archive", "--format=tar", `--output=${archive}`, "HEAD", "src"]);
  execFileSync("tar", ["-xmf", archive, "-C", tmp]);
  srcRoot = join(tmp, "src");
}

if (!existsSync(join(srcRoot, "lib/quant/live-decision.ts"))) {
  console.error(
    worktree
      ? "bist-charts has no src/lib/quant/live-decision.ts in its working tree."
      : "bist-charts HEAD has no src/lib/quant/live-decision.ts. Commit it there, or pass --worktree to bundle uncommitted files.",
  );
  if (tmp) rmSync(tmp, { recursive: true, force: true });
  process.exit(1);
}

const { build } = await import("esbuild");
const outfile = join(root, "engine/engine.mjs");
const stamp = `${commit.slice(0, 7)}${worktree ? " (working tree)" : ""}`;
const result = await build({
  entryPoints: [join(root, "engine/entry.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  alias: { "@": srcRoot },
  outfile,
  legalComments: "none",
  metafile: true,
  logLevel: "warning",
  banner: { js: `// Generated by scripts/sync-engine.mjs from bist-charts ${stamp}. Do not edit: run npm run sync-engine.` },
});
if (tmp) rmSync(tmp, { recursive: true, force: true });

const bundle = readFileSync(outfile);
const inputs = Object.keys(result.metafile.inputs)
  .map((p) => p.replace(/^.*?\/src\//, "src/"))
  .sort();
const info = {
  source: "bist-charts",
  commit,
  commitDate,
  worktree,
  dirtyFiles: worktree ? dirty : [],
  builtAt: new Date().toISOString(),
  bundleSha256: createHash("sha256").update(bundle).digest("hex"),
  inputs,
};
writeFileSync(join(root, "engine/engine.json"), JSON.stringify(info, null, 2) + "\n");

// Golden trade lists: fixed strategies on the bundled fixtures, with the bot's default execution settings.
const engine = await import(`${pathToFileURL(outfile).href}?v=${Date.now()}`);
const { goldenCases } = await import(pathToFileURL(join(root, "src/golden-cases.js")).href);
const golden = {};
for (const c of goldenCases(root, engine)) {
  const run = engine.runPresetStrategyBacktest(c.candles, c.strategy, c.options);
  golden[c.name] = {
    trades: run.trades.length,
    finalEquity: run.equityCurveClose.at(-1) ?? null,
    sha256: createHash("sha256").update(JSON.stringify(run.trades)).digest("hex"),
  };
}
const goldenPath = join(root, "engine/golden.json");
const previous = existsSync(goldenPath) ? JSON.parse(readFileSync(goldenPath, "utf8")).cases : null;
writeFileSync(goldenPath, JSON.stringify({ commit, cases: golden }, null, 2) + "\n");

console.log(`engine/engine.mjs built from bist-charts ${stamp}, ${inputs.length} source files, ${(bundle.length / 1024).toFixed(0)} KB`);
if (worktree && dirty.length > 0) console.log(`Uncommitted bist-charts files bundled:\n  ${dirty.join("\n  ")}`);
if (previous) {
  const changed = Object.keys(golden).filter((k) => previous[k]?.sha256 !== golden[k].sha256);
  if (changed.length === 0) console.log(`Golden trades unchanged (${Object.keys(golden).length} strategies).`);
  else {
    console.log(`Trading behaviour changed for ${changed.length} of ${Object.keys(golden).length} golden strategies:`);
    for (const k of changed) {
      const p = previous[k];
      const g = golden[k];
      console.log(`  ${k}: ${p ? `${p.trades} trades, equity ${p.finalEquity}` : "new"} -> ${g.trades} trades, equity ${g.finalEquity}`);
    }
  }
}
